-- Odyssey core schema. Timestamps are epoch milliseconds (UTC). JSON documents are stored as text.
-- Written to run unchanged on PostgreSQL and on H2 (used by tests).

CREATE TABLE tenants (
    id VARCHAR(36) PRIMARY KEY,
    slug VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    vertical VARCHAR(64) NOT NULL,
    config TEXT NOT NULL
);

CREATE TABLE users (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(36) NOT NULL,
    phone VARCHAR(32) NOT NULL,
    name VARCHAR(200) NOT NULL,
    role VARCHAR(32) NOT NULL,
    provider_id VARCHAR(36),
    pin_hash VARCHAR(200),
    pin_failures INTEGER NOT NULL DEFAULT 0,
    locked_until BIGINT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_users_phone UNIQUE (tenant_id, phone)
);
CREATE INDEX ix_users_provider ON users (provider_id);

CREATE TABLE providers (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(36) NOT NULL,
    name VARCHAR(200) NOT NULL,
    owner_user_id VARCHAR(36) NOT NULL,
    status VARCHAR(32) NOT NULL,
    commission_bps INTEGER,
    documents TEXT NOT NULL,
    bank TEXT,
    review_note TEXT,
    created_at BIGINT NOT NULL
);
CREATE INDEX ix_providers_tenant ON providers (tenant_id, status);

CREATE TABLE locations (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(36) NOT NULL,
    provider_id VARCHAR(36) NOT NULL,
    name VARCHAR(200) NOT NULL,
    address VARCHAR(500) NOT NULL,
    lat DOUBLE PRECISION NOT NULL,
    lng DOUBLE PRECISION NOT NULL,
    timezone VARCHAR(64) NOT NULL,
    open_time VARCHAR(5) NOT NULL,
    close_time VARCHAR(5) NOT NULL,
    slot_minutes INTEGER NOT NULL,
    capacity INTEGER NOT NULL,
    auto_accept BOOLEAN NOT NULL,
    is_open BOOLEAN NOT NULL,
    amenities TEXT NOT NULL,
    photo_url VARCHAR(500),
    rating_avg DOUBLE PRECISION NOT NULL DEFAULT 0,
    rating_count INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX ix_locations_provider ON locations (provider_id);
CREATE INDEX ix_locations_tenant ON locations (tenant_id);

CREATE TABLE catalog_items (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(36) NOT NULL,
    location_id VARCHAR(36) NOT NULL,
    name VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    category VARCHAR(100) NOT NULL,
    duration_minutes INTEGER NOT NULL,
    active BOOLEAN NOT NULL,
    prices TEXT NOT NULL
);
CREATE INDEX ix_items_location ON catalog_items (location_id);

CREATE TABLE blocks (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(36) NOT NULL,
    location_id VARCHAR(36) NOT NULL,
    starts_at BIGINT NOT NULL,
    ends_at BIGINT NOT NULL,
    reason VARCHAR(500) NOT NULL,
    created_by VARCHAR(36) NOT NULL
);
CREATE INDEX ix_blocks_location ON blocks (location_id, starts_at);

CREATE TABLE orders (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(36) NOT NULL,
    code VARCHAR(16) NOT NULL,
    customer_id VARCHAR(36),
    customer_name VARCHAR(200) NOT NULL,
    customer_phone VARCHAR(32) NOT NULL,
    provider_id VARCHAR(36) NOT NULL,
    location_id VARCHAR(36) NOT NULL,
    location_name VARCHAR(200) NOT NULL,
    asset_label VARCHAR(200),
    variant_key VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    source VARCHAR(16) NOT NULL,
    starts_at BIGINT NOT NULL,
    ends_at BIGINT NOT NULL,
    lines TEXT NOT NULL,
    subtotal_minor BIGINT NOT NULL,
    tax_minor BIGINT NOT NULL,
    fee_minor BIGINT NOT NULL,
    total_minor BIGINT NOT NULL,
    commission_bps INTEGER NOT NULL,
    commission_minor BIGINT NOT NULL,
    hold_expires_at BIGINT,
    cancellation_reason TEXT,
    settled BOOLEAN NOT NULL DEFAULT FALSE,
    payout_id VARCHAR(36),
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);
CREATE INDEX ix_orders_location ON orders (location_id, starts_at);
CREATE INDEX ix_orders_customer ON orders (customer_id);
CREATE INDEX ix_orders_provider ON orders (provider_id, starts_at);
CREATE INDEX ix_orders_tenant ON orders (tenant_id, created_at);

CREATE TABLE order_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(36) NOT NULL,
    from_status VARCHAR(32),
    to_status VARCHAR(32) NOT NULL,
    action VARCHAR(64) NOT NULL,
    actor_id VARCHAR(36),
    note TEXT,
    occurred_at BIGINT NOT NULL
);
CREATE INDEX ix_events_order ON order_events (order_id);

CREATE TABLE payments (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(36) NOT NULL,
    order_id VARCHAR(36) NOT NULL UNIQUE,
    amount_minor BIGINT NOT NULL,
    refunded_minor BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL,
    method VARCHAR(32) NOT NULL,
    gateway_ref VARCHAR(100),
    created_at BIGINT NOT NULL
);

CREATE TABLE ledger_entries (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(36) NOT NULL,
    order_id VARCHAR(36),
    txn_id VARCHAR(36) NOT NULL,
    type VARCHAR(32) NOT NULL,
    account VARCHAR(64) NOT NULL,
    amount_minor BIGINT NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX ix_ledger_order ON ledger_entries (order_id);
CREATE INDEX ix_ledger_tenant ON ledger_entries (tenant_id, created_at);

CREATE TABLE payouts (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(36) NOT NULL,
    provider_id VARCHAR(36) NOT NULL,
    amount_minor BIGINT NOT NULL,
    order_count INTEGER NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX ix_payouts_tenant ON payouts (tenant_id, created_at);

CREATE TABLE reviews (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(36) NOT NULL,
    order_id VARCHAR(36) NOT NULL UNIQUE,
    location_id VARCHAR(36) NOT NULL,
    customer_name VARCHAR(200) NOT NULL,
    rating INTEGER NOT NULL,
    comment TEXT NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX ix_reviews_location ON reviews (location_id, created_at);

CREATE TABLE assets (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(36) NOT NULL,
    owner_user_id VARCHAR(36) NOT NULL,
    kind VARCHAR(32) NOT NULL,
    label VARCHAR(200) NOT NULL,
    attributes TEXT NOT NULL
);
CREATE INDEX ix_assets_owner ON assets (owner_user_id);

CREATE TABLE audit_log (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(36) NOT NULL,
    actor_id VARCHAR(36),
    actor_role VARCHAR(32) NOT NULL,
    action VARCHAR(64) NOT NULL,
    entity VARCHAR(32) NOT NULL,
    entity_id VARCHAR(36),
    detail TEXT NOT NULL,
    occurred_at BIGINT NOT NULL
);
CREATE INDEX ix_audit_tenant ON audit_log (tenant_id, occurred_at);

CREATE TABLE idempotency_keys (
    tenant_id VARCHAR(36) NOT NULL,
    scope VARCHAR(64) NOT NULL,
    idem_key VARCHAR(100) NOT NULL,
    response TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (tenant_id, scope, idem_key)
);
